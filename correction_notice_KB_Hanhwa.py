def section(f, origname):
    """정정사항 파일에 들어갈 정정 1건 블록."""
    out = ["---", "", "## 정정 #%d" % f["no"], "",
           "| 항목 | 값 |", "|---|---|",
           "| 위치 | `%s` %d줄 |" % (origname, f["line"]),
           "| 경로 | %s |" % f["path"].replace("|", "\\|"),
           "| 사유 | %s |" % f["reason"],
           "| 변경 | %s |" % f["diff"]]
    if f.get("anchor"):
        out.append("| 앵커 | `%s...` |" % f["anchor"].replace("|", "\\|"))
    out += ["", "### 정정후 내용 (유효)", ""]
    if f.get("title"):
        out += [f["title"], ""]
    if f.get("unit"):
        out += [f["unit"], ""]
    out += f["after"] + [""]
    return out


def write(path, lines):
    io.open(path, "w", encoding="utf-8").write("\n".join(lines))
    print("[OK] %-46s %8d B" % (os.path.basename(path),
                                len("\n".join(lines).encode("utf-8"))))


def write_marked(L, fixes, metaline, dst, rcpt, patchname):
    """원본 사본에 메타 한 줄 + 정정 위치 마커를 넣는다. 원본은 안 건드림."""
    M = list(L)
    # 마커는 뒤에서 앞으로 넣어야 줄번호가 안 밀린다
    for f in sorted(fixes, key=lambda x: -x["line"]):
        M.insert(f["line"] - 1,
                 "<!-- [정정있음 #%d] %s 로 정정됨 | %s | 정정후: %s -->"
                 % (f["no"], rcpt, f["diff"], patchname))
    # 머리말 메타 한 줄 (기존 '>' 줄 뒤에). 두 번 돌려도 안전하게 먼저 제거
    M = [l for l in M if not l.startswith("> 정정:")]
    ins = max((i for i, l in enumerate(M[:6]) if l.startswith(">")), default=0) + 1
    M.insert(ins, metaline)
    write(dst, M)


